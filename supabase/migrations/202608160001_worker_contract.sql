-- Publish real status changes to Supabase Realtime for future clients. The
-- frontend also polls, so it still works if a websocket is unavailable.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'linkdub_jobs'
  ) then
    alter publication supabase_realtime add table public.linkdub_jobs;
  end if;
end
$$;

